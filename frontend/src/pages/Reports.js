import React from "react";
import { FileText, Download, Printer } from "lucide-react";
import { toast } from "sonner";
import { Card, Caption, SectionHeader } from "@/components/vo/ui";

function buildMarkdown(r) {
  const e = r.executive || {};
  const s = r.strategic || {};
  const cust = r.customer || {};
  const caps = r.capabilities || {};
  const L = [];
  L.push(`# VOCIS Intelligence Report — ${r.dataset_name || "Dataset"}`);
  L.push(`_Generated ${new Date(r.created_at).toLocaleString()}_\n`);
  L.push(`## 1. Executive Summary`);
  if (e.headline) L.push(`**${e.headline}**\n`);
  if (e.executive_summary) L.push(e.executive_summary + "\n");
  L.push(`## 2. Customer Intelligence`);
  const sn = cust.sentiment || {};
  L.push(`- Records analyzed: ${sn.total}`);
  L.push(`- Sentiment: ${sn.positive} positive, ${sn.negative} negative, ${sn.neutral} neutral (avg ${sn.avg_score})`);
  if (e.biggest_pain) L.push(`- Biggest pain: ${e.biggest_pain}`);
  if (e.strongest_signal) L.push(`- Strongest signal: ${e.strongest_signal}`);
  if (e.customer_demand) L.push(`- Customer demand: ${e.customer_demand}`);
  L.push(`\n## 3. Major Issues (priority-ranked)`);
  (r.issues || []).slice(0, 8).forEach((i) => {
    L.push(`\n### ${i.name} — ${i.priority?.toUpperCase()} (score ${i.priority_score})`);
    L.push(`- ${i.size} mentions · ${Math.round(i.share * 100)}% share · ${Math.round(i.neg_share * 100)}% negative${i.growth != null ? ` · ${i.growth > 0 ? "+" : ""}${Math.round(i.growth * 100)}% growth` : ""}`);
    if (i.narrative) L.push(`\n${i.narrative}`);
  });
  if (r.temporal?.emerging?.length) {
    L.push(`\n## 4. Emerging Issues`);
    r.temporal.emerging.forEach((em) => L.push(`- ${em.name || em.keywords?.join(" ")}: +${Math.round(em.growth * 100)}% (${em.size} mentions, ${Math.round(em.neg_share * 100)}% negative)`));
  }
  if (r.product?.products?.length) {
    L.push(`\n## 5. Product Intelligence`);
    r.product.products.forEach((p) => L.push(`- ${p.product}: avg sentiment ${p.avg_sentiment}, ${Math.round(p.neg_share * 100)}% negative (${p.count} records)`));
  }
  if (r.competitive) {
    L.push(`\n## 6. Competitive Intelligence`);
    if (r.competitive.narrative) L.push(r.competitive.narrative);
  }
  if (r.market?.market_summary) {
    L.push(`\n## 7. Market Intelligence (external)`);
    L.push(r.market.market_summary);
    (r.market.sources || []).forEach((src, i) => L.push(`- [${i}] ${src.title} — ${src.url}`));
  }
  L.push(`\n## 8. Strategic Priorities`);
  (s.priorities || []).forEach((p) => L.push(`- **${p.title}**: ${p.rationale}`));
  L.push(`\n## 9. Recommendations & Investigation`);
  (s.needs_investigation || []).forEach((n) => L.push(`- ${n.question} (${n.why})`));
  L.push(`\n## 10. Methodology`);
  L.push(`Sentiment scored deterministically (VADER + rating blend). Themes discovered via sentence-embedding clustering (no predefined categories). Priority computed from a transparent weighted model (volume, negativity, severity, breadth, growth, recency). Narratives generated by GPT-5.4 reasoning strictly over computed evidence.`);
  L.push(`\n## 11. Data Limitations`);
  L.push(`- Temporal analysis: ${caps.temporal ? "available" : "unavailable (no reliable dates)"}`);
  L.push(`- Competitive analysis: ${caps.competitive ? "available" : "unavailable (single brand)"}`);
  L.push(`- Product analysis: ${caps.product ? "available" : "unavailable (no product field)"}`);
  L.push(`\nVOCIS reports customer-facing patterns; it does not assert operational root cause without supporting data.`);
  return L.join("\n");
}

export default function Reports({ report }) {
  const download = () => {
    const md = buildMarkdown(report);
    const blob = new Blob([md], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url; a.download = `VOCIS_Report_${(report.dataset_name || "dataset").replace(/\s+/g, "_")}.md`;
    a.click(); URL.revokeObjectURL(url);
    toast.success("Report downloaded (Markdown).");
  };

  const e = report.executive || {};
  const s = report.strategic || {};
  const sections = [
    { n: "01", t: "Executive Summary", body: e.executive_summary },
    { n: "02", t: "Biggest Customer Pain", body: e.biggest_pain },
    { n: "03", t: "What Changed", body: e.what_changed },
    { n: "04", t: "Strategic Synthesis", body: s.synthesis },
    { n: "05", t: "Recommended Attention", body: e.recommended_attention },
  ].filter((x) => x.body);

  return (
    <div>
      <SectionHeader eyebrow="Reports" title="Professional intelligence dossier"
        subtitle="A consulting-grade document assembled from the analysis — not a dump of dashboard charts."
        right={
          <div className="flex gap-2">
            <button onClick={() => window.print()} data-testid="report-print-button"
              className="inline-flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.03] px-3 py-2 text-xs font-medium text-slate-200 hover:border-white/25 transition-colors">
              <Printer size={14} /> Print
            </button>
            <button onClick={download} data-testid="report-export-pdf-button"
              className="inline-flex items-center gap-1.5 rounded-lg bg-indigo-500 px-3 py-2 text-xs font-semibold text-white hover:bg-indigo-400 transition-colors">
              <Download size={14} /> Download report
            </button>
          </div>
        } />

      <Card hover={false} className="vo-grain overflow-hidden p-10">
        <div className="border-b border-white/10 pb-6">
          <div className="flex items-center gap-2"><FileText size={16} className="text-indigo-300" /><Caption className="text-indigo-300/70">VOCIS Intelligence Report</Caption></div>
          <h1 className="mt-3 text-3xl font-extrabold tracking-tight text-white font-display">{report.dataset_name}</h1>
          <p className="mt-2 text-xs font-mono text-slate-500">Generated {new Date(report.created_at).toLocaleString()} · {report.coverage?.records} records · {report.coverage?.themes} themes</p>
        </div>

        {e.headline && <p className="mt-6 text-lg font-semibold leading-relaxed text-slate-100 font-display">{e.headline}</p>}

        <div className="mt-8 space-y-8">
          {sections.map((sec) => (
            <div key={sec.n} className="grid grid-cols-[48px_1fr] gap-4">
              <div className="font-mono text-sm text-slate-600">{sec.n}</div>
              <div>
                <h3 className="text-sm font-semibold uppercase tracking-wide text-slate-300 font-display">{sec.t}</h3>
                <p className="mt-2 text-[15px] leading-[1.75] text-slate-300">{sec.body}</p>
              </div>
            </div>
          ))}

          <div className="grid grid-cols-[48px_1fr] gap-4">
            <div className="font-mono text-sm text-slate-600">06</div>
            <div>
              <h3 className="text-sm font-semibold uppercase tracking-wide text-slate-300 font-display">Priority Issues</h3>
              <div className="mt-3 space-y-3">
                {(report.issues || []).slice(0, 6).map((i, idx) => (
                  <div key={idx} className="rounded-lg border border-white/[0.06] bg-white/[0.015] p-4">
                    <div className="flex items-center justify-between">
                      <span className="text-sm font-semibold text-slate-100">{i.name}</span>
                      <span className="font-mono text-xs text-slate-500">{i.priority} · {i.priority_score}</span>
                    </div>
                    {i.narrative && <p className="mt-2 text-xs text-slate-400 leading-relaxed">{i.narrative}</p>}
                  </div>
                ))}
              </div>
            </div>
          </div>
        </div>
      </Card>
    </div>
  );
}
